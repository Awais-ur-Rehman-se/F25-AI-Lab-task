def word_spans(text):
    return [
        (m.start(), m.end())
        for m in re.finditer(r"\S+", text)
    ]


def windows(text, size=40, overlap=0, offset=0):

    if size <= 0 or overlap < 0 or overlap >= size:
        raise ValueError("Invalid size or overlap")

    spans = word_spans(text)
    result = []

    step = size - overlap

    for i in range(0, len(spans), step):
        j = min(i + size, len(spans))

        start = offset + spans[i][0]
        end = offset + spans[j - 1][1]

        result.append((start, end))

        if j == len(spans):
            break

    return result


def sentence_chunks(text, size=40):

    if size <= 0:
        raise ValueError("Size must be positive")

    cuts = [0]

    for m in re.finditer(r"[.!?]\s+", text):
        cuts.append(m.end())

    cuts.append(len(text))

    result = []
    pending = None
    count = 0

    for a, b in zip(cuts, cuts[1:]):
        segment = text[a:b]
        n = len(segment.split())

        if n == 0:
            continue

        if n > size:
            if pending is not None:
                result.append(pending)

            result.extend(windows(segment, size, 0, a))

            pending = None
            count = 0

        elif pending is not None and count + n <= size:
            pending = (pending[0], b)
            count += n

        else:
            if pending is not None:
                result.append(pending)

            pending = (a, b)
            count = n

    if pending is not None:
        result.append(pending)

    return result


def make_chunks(docs, strategy):

    chunks = []

    for doc_id, text in docs.items():

        if strategy == "sentence":
            spans = sentence_chunks(text, 40)

        elif strategy in ("0", "10"):
            spans = windows(text, 40, int(strategy))

        else:
            raise ValueError("Unknown strategy")

        for i, (start, end) in enumerate(spans):

            chunk = {
                "id": f"{doc_id}:{strategy}:{i}",
                "doc": doc_id,
                "strategy": strategy,
                "start": start,
                "end": end,
                "text": text[start:end]
            }

            chunks.append(chunk)

    return chunks


def check_labels(chunks, doc_id):

    rule, exception = LABELS[doc_id]

    for chunk in chunks:
        if chunk["doc"] == doc_id:
            if rule in chunk["text"] and exception in chunk["text"]:
                return True

    return False


