import re

samples = [
    "Hello, world!",
    "Where is my assignment?",
    "student@gmail.com",
    "CS4944 version 2.1",
    "",
    "آج موسم اچھا ہے"
]

for text in samples:
    whitespace = text.split()
    regex = re.findall(r"\b\w+\b", text, flags=re.UNICODE)

    print("Original Text:", repr(text))
    print("Whitespace Tokens:", whitespace)
    print("Whitespace Count:", len(whitespace))
    print("Regex Tokens:", regex)
    print("Regex Count:", len(regex))
    print("------------------------------")


try:
    from sentence_transformers import SentenceTransformer

    model = SentenceTransformer(
        "sentence-transformers/all-MiniLM-L6-v2",
        device="cpu"
    )

    for text in samples[:2]:
        tokens = model.tokenizer.tokenize(text)

        print("Original:", text)
        print("Model Tokens:", tokens)
        print("Model Token Count:", len(tokens))

except Exception as error:
    print("Model tokenizer unavailable:", error)


print("\nTwo Differences:")
print("1. Whitespace keeps punctuation attached; regex removes it.")
print("2. Whitespace keeps words together; regex separates punctuation.")

print("\nNormalization Risk:")
print("Removing important words like 'not' can change sentence meaning.")
print("Unicode regex is not a complete multilingual tokenizer.")